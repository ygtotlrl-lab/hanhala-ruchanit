-- ⛔ **רץ במסד** — ⚠️ נמדד בסבב 91: `ys_students_rows.cohort_year` אינה
--    קיימת עוד. ⛔ מיגרציה שכבר רצה אינה נערכת, ולכן השינוי הוא קובץ חדש.
--
-- ⭐ **מה שהוליד אותה:** שני שדות לאותו מושג — `cycle` ו-`cohortYear`.
--    ⚠️ `cycle` נגזר משנת הלימודים ונכתב בהשבתה ובקידום השכבה;
--    `cohortYear` הוא הכתיב הישן, ⛔ ואף מסלול אינו כותב אותו עוד.
--    ⛔ שני מקורות אמת לאותו ערך הם הכרעה בלי מפתח.
--
-- ⚠️ **הנמדד במסד לפני הכתיבה** (71 שורות): עשר נושאות `cohortYear`,
--    ⭐ ולכל עשר יש **גם** `cycle` שאינו ריק — ⛔ כלומר אפס שורות שבהן
--    הכתיב הישן הוא הערך היחיד, והנפילה-חזרה שהוסרה מהקוד לא נבחרה מעולם.
--    ⚠️ בשמונה מהן ההפרש הוא כתיב בלבד, ⛔ ובשתיים השנים עצמן נבדלות —
--    ⭐ ובשתיים האלה `cycle` הוא הערך שנרשם אחרון והוא זה שהוצג,
--    ⛔ ולכן אין כאן ערך שאובד.
--
-- ⛔ **החותמת אינה נגעת** — ⚠️ `updated_at` כאן הוא `bigint` שהמכשיר
--    מייצר, ⭐ והוא מנוע ההכרעה במיזוג: ⛔ קידומו היה הופך את השרת לחדש
--    מכל מכשיר ודורס עריכה אמיתית שטרם עלתה. ⚠️ המחיר המודע: מכשיר שכבר
--    מחזיק את השורה במטמון לא ימשוך אותה מחדש — ⛔ ואין בכך נזק, ⭐ שאין
--    עוד קוד שקורא את השדה.
--
-- ⛔ **אין `delete` ואין שינוי סכימה** — ⚠️ המפתח יושב בתוך `data` שהוא
--    `jsonb`, ⭐ וגריעתו היא `update` על אותה שורה.
-- ============================================================================

update public.ys_students_rows
   set data = data - 'cohortYear'
 where data ? 'cohortYear';

-- ⛔ שער שקילות — ⚠️ אחרי ההרצה אין שורה שנושאת את המפתח: ⭐ המיגרציה
--    נכשלת ברעש במקום להשאיר מצב חלקי.
do $$
declare left_over int;
begin
  select count(*) into left_over from public.ys_students_rows where data ? 'cohortYear';
  if left_over <> 0 then
    raise exception '020: נותרו % שורות עם cohortYear והצפוי אפס', left_over;
  end if;
end $$;
