-- ⛔ **רץ במסד** — ⚠️ הוחל בסבב 92 ואומת: אפס רשומות עם `updated_at = 0`
--    בשתי הטבלאות. ⛔ מיגרציה שכבר רצה אינה נערכת — שינוי נוסף הוא קובץ חדש.
--
-- ⚠️ **הבעיה שנמדדה:** ייבוא חד-פעמי של נתוני שינה היסטוריים (2026-05-23 עד
--    2026-06-24) נכתב ישירות למסד ב-2026-08-26 ⛔ בלי חותמת: ⭐ 940 מתוך 988
--    ב-`ys_sleep_marks` ו-20 מתוך 21 ב-`ys_sleep_sessions` נשאו `updated_at = 0`.
--    ⛔ ואפס אינו «לא ידוע» אלא **הישן ביותר** — ⚠️ כל עריכה מנצחת אותו, גם
--    שגויה, ⭐ והכשל שקט לחלוטין.
--
-- ⛔ **החותמת נגזרת מהרשומה עצמה ⛔ ולא מ-`now()`** — ⚠️ `now()` היה מסמן את
--    הישן כטרי ביותר, ⭐ ו-`synced_at` (מועד ההגעה לשרת) היה מסמן רשומה מחודש
--    מאי כחדשה מאוגוסט. ⛔ הערך הוא **`date_iso` בצהריים מקומיים**, ⚠️ בדיוק
--    מה ש-`_ysRecTs` מחשבת בדפדפן — ⭐ ולכן המסד מתכנס למה שהקוד כבר גוזר,
--    ⛔ ודחיפה עתידית של אותה רשומה אינה מזיזה אותה.
--
-- ⛔ אידמפוטנטי: התנאי הוא `updated_at = 0`, ⚠️ והרצה שנייה אינה נוגעת בדבר.

update public.ys_sleep_marks
   set updated_at = (extract(epoch from ((date_iso::date + time '12:00')
                     at time zone 'Asia/Jerusalem')) * 1000)::bigint
 where updated_at = 0
   and date_iso is not null
   and date_iso ~ '^\d{4}-\d{2}-\d{2}$';

update public.ys_sleep_sessions
   set updated_at = (extract(epoch from ((date_iso::date + time '12:00')
                     at time zone 'Asia/Jerusalem')) * 1000)::bigint
 where updated_at = 0
   and date_iso is not null
   and date_iso ~ '^\d{4}-\d{2}-\d{2}$';
