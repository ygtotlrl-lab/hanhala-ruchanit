-- 011_users_drop_plaintext_password.sql — הסרת הסיסמה הגלויה מ-`ys_users`
-- ============================================================================
--
-- ⛔⛔ **נכתב ולא רץ.** ⛔ ההרצה היא פעולת מנהל, ⛔ ואין להריץ מתוך סשן.
--
-- ⭐ **מה שהוליד אותה:** `ys_users.password_hash` החזיקה את
--    הסיסמה ב**טקסט גלוי**, והייתה **המפתח שפותח את הכניסה**: `doLogin`,
--    `confirmSwitch` ו-`changeMyPassword` כולם השוו מולה מחרוזות ישירות.
--    מפתח ה-anon של Supabase יושב ב-`index.html` **הציבורי**, ו-RLS כאן
--    הוא `USING (true)` — כלומר כל מי שקרא את קוד המקור יכול היה לשלוף את
--    כל הסיסמאות ולהיכנס בזהות של כל אחד מאנשי הצוות.
--
-- ⚠️ **וזו הייתה החלטה מתועדת, לא פספוס.** המנהל בחר בטקסט גלוי כדי לראות
--    ולנהל סיסמאות מתוך «ניהול משתמשים», וכלל ברזל 9 מייחד את ההכרעה הזו
-- לו בלבד. ⭐ **ההחלטה בוטלה על ידו**, וזו
--    המיגרציה שסוגרת אותה.
--
-- ⭐ **מה שכבר נעשה בקוד, ובלעדיו אסור להריץ כאן דבר:**
--    שלושת מסלולי ההשוואה עברו לאימות מול `pass_salt`+`pass_fp` — טביעת
--    PBKDF2-SHA256 ב-100,000 סיבובים עם מלח פר-משתמש. כלומר העמודה
-- **נכתבת ואינה נקראת**. ⚠️ נבדק לפני הכתיבה (`SELECT` בלבד,
-- (`SELECT` בלבד): כל ששת המשתמשים מחזיקים `pass_salt` ו-`pass_fp` באורך
--    64 — ולכן אף אחד לא ננעל בחוץ.
--
-- ═══ שני הצעדים, ו⛔ למה אסור לאחד אותם ═══════════════════════════════════
-- `password_hash` היא `NOT NULL` בלי `DEFAULT`. המשמעות: קוד שמפסיק לכתוב
-- אליה **לפני** שהאילוץ ירד מפיל כל `INSERT` של משתמש חדש. לכן:
--
--   צעד א (למטה) — הסרת `NOT NULL`. בטוח להרצה **עכשיו**: הוא אינו נוגע
--   בנתונים, ואינו שובר שום קוד קיים.
--
--   צעד ב (מוער) — מחיקת העמודה. ⛔ **רק אחרי** ש-`YS_PLAINTEXT_LEGACY_WRITE`
--   כובה ב-`index.html` ונפרס למכשירים, ואחרי שאומת שכניסה, מעבר-משתמש
-- ושינוי סיסמה עובדים. ⛔ הכיבוי והמחיקה בסבבים נפרדים — אחרת
--   אין חלון לגלות טעות.
--
-- ⚠️ **ומחיקת העמודה אינה מסירה את הסיסמאות מההיסטוריה:** הן יושבות גם
-- ב-`kv_backup`? ⛔ **לא** — `ys_users` מוחרגת מהגיבוי כולה,
--    וזה נבדק. אבל הן כן נראו ע"י כל מי שהחזיק את מפתח ה-anon עד היום,
--    ולכן ⭐ **הטיפול המלא הוא החלפת הסיסמאות של ששת המשתמשים** — פעולת
--    מנהל, אחרי צעד ב.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── צעד א — הסרת NOT NULL (אידמפוטנטי, בטוח להרצה מיידית) ──────────────────
alter table public.ys_users alter column password_hash drop not null;

