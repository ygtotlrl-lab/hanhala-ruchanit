-- ============================================================================
-- 018_drop_kv_keys.sql — שלושה-עשר מפתחות ה-`kv` יורדים
-- ============================================================================
--
-- ⛔⛔ **נכתב ולא רץ.** ⛔ ההרצה היא פעולת מנהל, ⛔ ואין להריץ מתוך סשן.
--
-- ⛔⛔ **תנאי מוקדם, ואין לעקוף אותו:** הגרסה שאינה קוראת מ-`kv` מותקנת בכל
--     מכשיר. ⚠️ מכשיר שנשאר על גרסה ישנה קורא משם, ⛔ ומחיקה לפניה מרוקנת
--     לו את המסך — ⭐ בלי הודעה, ובלי דרך לדעת שזה מה שקרה.
--
-- ⭐ **מה משתנה:** עשרת מפתחות ההגדרות עברו ל-`ys_settings` (`017`), ושלושת
--    מפתחות הנתונים עברו לטבלאות המובנות (`002`/`009`/`010`).
--    ⚠️ **השקילות נמדדה מול המסד לפני המחיקה**, בשני הכיוונים:
--    ⭐ 345 סדרי נוכחות · 988 סימוני שינה · 71 תלמידים · 21 סדרי שינה,
--    ⛔ ואפס רשומות שקיימות ב-`kv` בלבד.
--
-- ⛔ **`delete` ולא `drop table`** — ⚠️ טבלת `kv` משותפת לארבע האפליקציות
--    ⛔ ואינה של האפליקציה הזו: ⭐ מה שיורד הוא שורות בקידומת `ys_` בלבד,
--    ⛔ והטבלה נשארת.
--
-- ⛔ **והרשימה שמית ולא קידומת** — ⚠️ `key like 'ys_%'` היה תופס גם מפתח
--    עתידי שאיש לא בדק, ⛔ ומחיקה שאין לה שם היא מחיקה שאין לה מדידה.
--
-- ⚠️ **ומקורות הגיבוי אינם יורדים כאן** — ⛔ רשימת-ההיתר של הפינוי יושבת
--    במיגרציה שכבר רצה, ⚠️ ומפתח גיבוי שיצא מהרשימה אינו מתפנה לעולם:
--    ⭐ הסרתם היא קובץ נפרד, אחרי שהמחיקה הזו אומתה.
--
-- ⛔ **אידמפוטנטי** — ⚠️ הרצה חוזרת מוחקת אפס שורות ואינה נכשלת.
-- ============================================================================


-- ============================================================================
-- ⛔ שער מקדים — השקילות נבדקת שוב **ברגע ההרצה**. ⛔ להריץ לפני ה-DELETE.
-- ============================================================================
-- ⚠️ מדידה תקפה לרגע שבו נעשתה: ⛔ בין כתיבת הקובץ להרצתו עלול מכשיר ישן
--    לכתוב ל-`kv` מפתח שאין לו מקבילה, ⭐ ומחיקה שנשענת על מדידה ישנה
--    מוחקת בדיוק אותו.
do $$
declare miss text;
begin
  select string_agg(k.key, ', ') into miss
    from public.kv k
   where k.key in ('ys_perms','ys_attend_cfg','ys_sleep_cfg',
     'ys_reasons','ys_absence_reasons','ys_cls_years','ys_approvals',
     'ys_attend_treats','ys_settings_meta','ys_last_changed')
     and not exists (select 1 from public.ys_settings s where s.key = k.key);
  if miss is not null then
    raise exception '⛔ מפתחות הגדרות שאין להם מקבילה ב-ys_settings: % — לעצור', miss;
  end if;

  if (select count(*) from public.ys_sessions where not deleted) = 0
     or (select count(*) from public.ys_students_rows where not deleted) = 0 then
    raise exception '⛔ טבלת נתונים ריקה — לעצור ולהבין מדוע לפני שמוחקים את המקור';
  end if;
end $$;


-- ───────────────────────────────────────────────────────────────────────────
-- המחיקה עצמה
-- ───────────────────────────────────────────────────────────────────────────
delete from public.kv
 where key in ('ys_perms','ys_attend_cfg','ys_sleep_cfg','ys_reasons',
   'ys_absence_reasons','ys_cls_years','ys_approvals','ys_attend_treats',
   'ys_settings_meta','ys_last_changed','ys_students','ys_attend_sessions',
   'ys_sleep_sessions');
