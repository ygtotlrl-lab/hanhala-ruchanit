-- ⛔⛔ **הקובץ הזה אינו מיגרציה ואינו רץ.** כל ה-SQL שבו מוער, בכוונה.
--     מחיקת שורות מ-`kv_backup` היא מחיקת **נתוני גיבוי**, והיא מחייבת
--     אישור מפורש של המנהל (ר' «גישת Supabase» ב-CLAUDE.md). הסשן שכתב
--     אותו לא הריץ דבר ולא נגע בשורה אחת.
--
-- ⚠️ ובנוסף: `kv_backup` היא **יומן ראיות** — ל-`anon` ול-`authenticated`
--    יש בה `insert`+`select` בלבד (כלל ברזל 10 סעיף 9, סבב 29). כלומר
--    השאילתות שלמטה יכולות לרוץ **רק** מ-SQL Editor / `service_role`,
--    ולא מהאפליקציה. ⛔ ואין לפתוח לה `delete` כדי «להריץ פינוי מהקוד».
--
--
-- ── מה נמדד (סבב 30, `SELECT` בלבד) ────────────────────────────────────────
--
--   סה"כ                136 שורות · 5,940 kB · 2026-07-07 → 2026-08-13
--
--   מזה **גיבויים ידניים חד-פעמיים** — הקידומות `PRE_SYNC_UNIFY_`,
--   `PRE_ROUND3B_` ו-`ORPHAN_` — שורה אחת לכל מפתח, ~2.6MB יחד. אלה היו
--   נקודות החזרה של סבבים 3ב/11: הן אינן מצטברות, והן היחידות שתיעדו מצב
--   שכבר אינו קיים בשום מקום אחר.
--
--   ⚠️ **עובדה, ולא הנחה (סבב 35ג): 57 השורות האלה נמחקו ב-2026-08-18
--   ואינן ניתנות לשחזור** — הפרויקט על מסלול Free, שאינו כולל גיבויי
--   פרויקט. המדידה שלמעלה נשארת כפי שנמדדה בסבב 30, והיא מתארת מצב
--   שאינו קיים עוד.
--   ⛔ **האיסור העקרוני נשאר בתוקף לכל גיבוי `PRE_*`/`ORPHAN_*` עתידי**
--   (סבב 35ג) — הוא מה שמונע מהפינוי האוטומטי לגעת בנקודת חזרה שאין לה
--   עותק אחר, וזו בדיוק הסיבה שהם מחוץ לרשימת-ההיתר של `004`.
--
--   ומזה **הגיבוי היומי האוטומטי**, וכאן ההצטברות:
--     ys_attend_sessions   8 שורות · 2,289 kB  →  ~286 kB לשורה
--     ys_students         11 שורות ·    78 kB
--     sl_students         10 שורות ·   118 kB
--     sl_transactions      9 שורות ·    46 kB
--
--   ⚠️ **הממצא החשוב יותר מהנפח:** הגיבוי של hanhala **הפסיק לרוץ
--      ב-2026-07-20** — זו החותמת האחרונה של כל ארבעת המפתחות שלה — בעוד
--      ש-schar גיבתה גם היום (2026-08-13). כלומר במשך שלושה שבועות לא היה
--      גיבוי להנהלה ואיש לא ידע. זו בדיוק הסיבה ש«גובה לאחרונה» נוסף
--      ל«מידע טכני» בסבב 30: מנגנון שקט שנעצר נראה בדיוק כמו מנגנון שקט
--      שעובד.
--
--
-- ── מה נעשה בקוד במקום מחיקה (סבב 30) ──────────────────────────────────────
--
-- ⭐ **גיבוי דיפרנציאלי** — ערך שלא השתנה מאז הגיבוי האחרון אינו נכתב שוב.
--    ההשוואה היא מול חתימה מקומית (אורך + FNV-1a) ואינה מושכת דבר מהרשת.
--    זה מה שהפך את הרחבת הכיסוי לאפשרית: הנהלה עברה מארבעה מפתחות לארבעה
--    עשר, ו-yoman-avoda הצטרפה עם `tb_archive` שהוא **1.2MB** — כתיבה
--    יומית עיוורת שלו לבדו הייתה מוסיפה ~36MB בחודש.
--    ⛔ אין להסיר את ההשוואה הזו «כדי שהגיבוי יהיה ודאי»: הערך הזהה כבר
--    יושב ב-`kv_backup`, וכתיבתו שוב אינה מוסיפה שום ראיה.
--
--
-- ── ההצעה: שמירת N אחרונים לכל מפתח אוטומטי ────────────────────────────────
--
-- ⚠️ להרצה ידנית ע"י המנהל בלבד, ורק אחרי שהוא בדק את מה שהיא הולכת למחוק.
--    שלושת השלבים לפי הסדר; ⛔ אין לדלג על שלב 1.
--
-- שלב 1 — מה יימחק, בלי למחוק (חובה להריץ ולקרוא לפני שלב 3):
--
--   with ranked as (
--     select id, key, created_at,
--            row_number() over (partition by key order by created_at desc) rn
--     from public.kv_backup
--     where key not like 'PRE\_%' and key not like 'ORPHAN\_%'
--   )
--   select key, count(*) to_delete, min(created_at) oldest, max(created_at) newest
--   from ranked where rn > 30 group by key order by 2 desc;
--
-- שלב 2 — כמה מקום זה מפנה:
--
--   with ranked as (
--     select id, key, value,
--            row_number() over (partition by key order by created_at desc) rn
--     from public.kv_backup
--     where key not like 'PRE\_%' and key not like 'ORPHAN\_%'
--   )
--   select pg_size_pretty(sum(length(coalesce(value,'')))::bigint)
--   from ranked where rn > 30;
--
-- שלב 3 — המחיקה עצמה. ⛔ **אינה רצה כאן, ואין להסיר את ההערה מהקובץ הזה.**
--         העתקה ידנית ל-SQL Editor, אחרי שלבים 1–2:
--
--   -- with ranked as (
--   --   select id, row_number() over (partition by key order by created_at desc) rn
--   --   from public.kv_backup
--   --   where key not like 'PRE\_%' and key not like 'ORPHAN\_%'
--   -- )
--   -- delete from public.kv_backup b using ranked r
--   --  where b.id = r.id and r.rn > 30;
--
-- ⛔ שני התנאים ב-`where` אינם קישוט (סבב 30):
--    `key not like 'PRE\_%'` ו-`'ORPHAN\_%'` הם מה שמגן על הגיבויים
--    הידניים החד-פעמיים, שאינם מצטברים ושאין להם עותק אחר. מחיקה בלעדיהם
--    הייתה משמידה את נקודות החזרה של סבבים 3ב/11 — ⛔ בדיוק את מה שגיבוי
--    אמור למנוע. (הקו הנטוי לפני הקו התחתון הוא escape: ב-`LIKE` הוא תו
--    כללי, ובלעדיו התבנית תופסת גם מפתחות אחרים.)
--
-- ⚠️ למה 30 ולא מספר אחר: הגיבוי הוא יומי, ולכן 30 הוא כחודש היסטוריה לכל
--    מפתח. עם הגיבוי הדיפרנציאלי זהו למעשה חודש של **שינויים** ולא של ימים,
--    כלומר לרוב הרבה יותר מחודש. ⛔ אין לרדת מתחת ל-7 בלי החלטה מפורשת.
--
--
-- ── מה **לא** מוצע כאן, ובכוונה ────────────────────────────────────────────
-- ⛔ אין הצעה לפינוי אוטומטי מתוך האפליקציה (סבב 30) — היא הייתה מחייבת
--    `delete` ל-`anon`, כלומר לפתוח לכל מי שמחזיק את המפתח הציבורי דרך
--    למחוק גיבויים. זה בדיוק ההפך מכלל ברזל 10 סעיף 9.
-- ⛔ ואין הצעה ל-`truncate`, בשום ניסוח.
