-- ============================================================================
-- 034_revoke_schema_grants.sql — הרשאות סכימה שאינן זכות על נתון
-- ============================================================================
--
-- ⛔ **רץ במסד.**
--
-- ⛔⛔ **מה הקובץ עושה:** ⚠️ גורע `references` ו-`trigger` מ-`anon`
--    ומ-`authenticated` על `ys_settings` ועל `ys_users` — ⭐ ומשאיר
--    `select, insert, update` בלבד.
--
-- ⛔⛔ **הנימוק:** ⚠️ נמדד מול `information_schema.role_table_grants` שחמש
--    טבלאות בפרויקט המשותף נשאו חמש הרשאות במקום שלוש — ⭐ והשתיים
--    העודפות נכנסו בהגדרה שנעשתה בלוח הבקרה ולא במיגרציה: ⛔ אין בקוד
--    מסלול שיוצר מפתח זר או טריגר בתפקיד `anon`, ⚠️ ולכן הגריעה אינה
--    נוגעת באף מסלול חי.
--
-- ⛔ **ואין כאן `delete` ואין `truncate`** — ⚠️ נמדד שאינם מוענקים לאף
--    תפקיד באף אחת מ-28 הטבלאות שבשני הפרויקטים: ⭐ הגריעה היא של מה
--    שקיים ⛔ ולא הצהרה על מה שאינו.
--
-- ⛔ **אידמפוטנטי** — ⚠️ `revoke` על הרשאה שאינה קיימת אינו שגיאה.
--
-- ============================================================================

revoke references, trigger on table public.ys_settings from anon, authenticated;
revoke references, trigger on table public.ys_users    from anon, authenticated;
